// Builds TESTING.md from the JSON the tests write into tests/results/.
'use strict';
const fs = require('fs');
const path = require('path');

const RES = path.join(__dirname, 'results');
const read = (f) => JSON.parse(fs.readFileSync(path.join(RES, f), 'utf8'));
const pitch = read('pitch.json'), inst = read('instruments.json'), loud = read('loudness.json');
const before = read('before.json'), after = read('after.json');

const f1 = (v) => (v >= 0 ? '+' : '') + v.toFixed(1);
const pct = (db) => (Math.pow(10, db / 20) - 1) * 100;
const row = (cells) => '| ' + cells.join(' | ') + ' |';
const out = [];
const P = (s) => out.push(s);

P('# Testing');
P('');
P('Everything below is measured, not estimated: a headless Chromium renders the app\'s real audio graph into an');
P('`OfflineAudioContext`, and the tests measure the rendered samples. This file is generated by `node tests/report.js`');
P('from the JSON the tests write to `tests/results/`.');
P('');
P('## Running the tests');
P('');
P('Needs Node 18+ and Playwright\'s Chromium (`npx playwright install chromium` if it is not already installed).');
P('');
P('```sh');
P('cd tests && npm install          # once: installs Playwright');
P('npm run pitch                    # key x scale test, every melodic instrument (about 3 minutes)');
P('npm run instruments              # violin / cello tuning, timbre and bowing; French horn; limiter');
P('npm run loudness                 # peak and RMS of every instrument and pad');
P('npm run calibrate                # re-derive the LEVEL trims in index.html (only after changing a sound)');
P('npm run baseline -- ../index.html results/after.json   # same UI gestures on any version of the app');
P('npm run report                   # rebuild this file');
P('```');
P('');
P('## How the harness works');
P('');
P('- `tests/lib/browser.js` opens `index.html` in headless Chromium and, before the app\'s script runs, swaps');
P('  `AudioContext` for an `OfflineAudioContext` (48 kHz, stereo). Timed actions run at exact audio times by suspending');
P('  the offline render, so a test can press a key at 0.3 s and lift it at 1.05 s.');
P('- Notes are played the way a person plays them wherever that is possible: synthetic pointer events on the');
P('  piano keys, flute and horn cells, harmonica holes and the violin / cello fingerboard, and the real chord buttons on');
P('  the guitar. Bow strokes, whose speed comes from event timestamps, go through the same input functions the touch');
P('  handlers call (`bwDown` / `bwMove` / `bwTick`) with explicit times. These hooks only exist when the harness sets');
P('  `window.__PB_TEST__` before the page loads.');
P('- Expected notes come from `tests/lib/reference.js`, written from the musical definitions rather than copied from');
P('  the app, so a pass means the app\'s pitches and its labels both agree with music theory.');
P('- Pitch (`tests/lib/analysis.js`): YIN finds the period, then the power-weighted mean frequency of three harmonics');
P('  above 300 Hz is taken over the whole window from a Hann-windowed DFT. For detuned oscillator stacks (horn,');
P('  strings) and vibrato this is the average pitch a listener hears; on a clean tone it is exact to well under 0.1 cent.');
P('- Peak is the sample peak at the app\'s output, in dBFS. RMS is measured while the note sounds: from its start to');
P('  the last sample within 20 dB of its peak (reverb tail excluded, at most 1 s). "Phone-band RMS" is the RMS above');
P('  200 Hz (12 dB/octave high-pass), roughly what a phone speaker can reproduce.');
P('- A new Web Audio compressor starts fully clamped and takes about 0.2 s to open, so every measured note starts');
P('  0.3 s into the render. The app now bridges that window itself (see "First note after start-up" below).');
P('');

P('## What was wrong (measured on the version before this change)');
P('');
const bk = (n) => before.keys.find((k) => k.name === n);
P(`- **Key and scale.** Piano and guitar had no key or scale at all. The violin and cello ignored the key: the same`);
P(`  finger position played ${bk('Violin').key0.toFixed(2)} Hz in C and ${bk('Violin').key2.toFixed(2)} Hz in D (cello ${bk('Cello').key0.toFixed(2)} / ${bk('Cello').key2.toFixed(2)} Hz),`);
P('  because the key only moved the guide marks. The harmonica ignored the scale. Flute and horn did follow the key,');
P('  but every instrument kept its own copy of the scale tables, and only six of the ten scales existed.');
P('- **Violin and cello.** The tuning itself was right (open strings measured ' +
  before.strings.filter((s) => s.tab === 'violin').map((s) => s.f.toFixed(1)).join(', ') + ' Hz and ' +
  before.strings.filter((s) => s.tab === 'cello').map((s) => s.f.toFixed(1)).join(', ') + ' Hz).');
P('  They sounded alike because both used the same two-sawtooth recipe through similar filters, and a cello\'s low');
P('  register (65-220 Hz) is mostly below what a phone speaker plays, so what was left sounded like a violin.');
P('- **Loudness.** The master chain was volume 0.8 into a default `DynamicsCompressor` (threshold -24 dB, ratio 12,');
P('  30 dB knee), which squashed everything. Per-sound levels were never balanced: tabla Te and Ti peaked around');
P('  -25 dBFS, the drum pad closed hat at -15 dBFS with a mid hit. Kicks, toms and the bayan had 75-80% of their');
P('  energy below 200 Hz, which a phone speaker barely reproduces. A new compressor also starts clamped, so the');
P('  first note after the app woke up came out about 10 dB quiet.');
P('- **French horn.** Two sawtooths and a sine through a bright filter and a tanh distortion: buzzy, nothing like a horn.');
P('');

P('## Key x scale');
P('');
P('Every melodic instrument x all 12 keys x all 10 scales. Each case plays one octave of the scale (or ten harmonica');
P('holes, every scale note on the violin / cello D / G string, or the six strings of the first chord on the guitar)');
P('through the instrument\'s own touch handlers, measures each note, and checks it against the reference note and');
P('against the label on screen. Pass: within 5 cents, label matches, and the 12 keys give 12 different sets of notes.');
P('');
P(row(['Instrument', 'Cases', 'Notes measured', 'Failed', 'Worst error (cents)', 'Mean error (cents)', 'Keys give different pitches']));
P(row(['---', '---:', '---:', '---:', '---:', '---:', '---']));
pitch.summary.forEach((s) => P(row([s.tab, s.cases, s.notes, s.failed, s.maxCents.toFixed(2), s.meanCents.toFixed(2), s.keysDistinct ? 'yes' : 'NO'])));
const tot = pitch.summary.reduce((a, s) => ({ c: a.c + s.cases, n: a.n + s.notes, f: a.f + s.failed }), { c: 0, n: 0, f: 0 });
P(row(['**all**', `**${tot.c}**`, `**${tot.n}**`, `**${tot.f}**`, '', '', '']));
P('');
P('Notes: the guitar\'s small error is its deliberate ±2 cent humanising detune. A fretless board in the chromatic');
P('scale offers every semitone in every key, so for violin and cello in "Chromatic" the key changes only the root mark');
P('and sargam labels; there the different-pitches check does not apply. The bowed instruments snap to the scale by');
P('default ("Snap to scale" is on); with it off they are free fretless instruments again.');
P('');

P('## Violin, cello, bowing, horn and the limiter');
P('');
P(row(['Test', 'Result', 'Measured']));
P(row(['---', '---', '---']));
inst.forEach((t) => P(row([t.name, t.ok ? 'pass' : '**FAIL**', t.detail.replace(/\|/g, '/')])));
P('');

P('## Loudness: before and after');
P('');
P('The same gestures, played through the UI of the old and the new version at the default master volume');
P('(old 0.8, new 100%). Keyboard keys play drums at velocity 0.9; pointer hits land in the middle of the pad.');
P('');
P(row(['Sound', 'Peak before', 'Peak after', 'RMS before', 'RMS after', 'Phone-band RMS before', 'after', 'Change (phone band)']));
P(row(['---', '---:', '---:', '---:', '---:', '---:', '---:', '---:']));
let sum = 0, sumAll = 0, n = 0;
before.loudness.forEach((b) => {
  const a = after.loudness.find((x) => x.name === b.name);
  if (!a) return;
  const d = a.rmsPhone - b.rmsPhone, dAll = a.rms - b.rms;
  sum += d; sumAll += dAll; n++;
  P(row([b.name, b.peak.toFixed(1), a.peak.toFixed(1), b.rms.toFixed(1), a.rms.toFixed(1), b.rmsPhone.toFixed(1), a.rmsPhone.toFixed(1), `${f1(d)} dB (${f1(pct(d))}%)`]));
});
P('');
P(`**Overall:** across these ${n} sounds the output rose by ${f1(sumAll / n)} dB RMS on average (${f1(pct(sumAll / n))}% in amplitude),`);
P(`and by ${f1(sum / n)} dB (${f1(pct(sum / n))}%) in the band a phone speaker plays. RMS here is over a fixed 1 s window from the note.`);
P('');
const lowNames = ['Drums kick', 'Drums low tom', 'Drums high tom', 'Tabla bayan Ge', 'Tabla bayan Ke', 'Drum pad Kick (mid hit)', 'Drum pad Sub (mid hit)'];
P('### Low sounds on a phone speaker');
P('');
P('Share of each sound\'s energy above 200 Hz, before and after adding upper harmonics and a click transient:');
P('');
P(row(['Sound', 'Above 200 Hz before', 'after']));
P(row(['---', '---:', '---:']));
lowNames.forEach((nm) => {
  const b = before.loudness.find((x) => x.name === nm), a = after.loudness.find((x) => x.name === nm);
  if (b && a) P(row([nm, (100 * b.above200).toFixed(0) + '%', (100 * a.above200).toFixed(0) + '%']));
});
P('');

P('## Normalisation: every instrument and pad');
P('');
P('One medium-velocity note each (velocity 0.7; held instruments at 65% breath or a medium bow; harmonica at its');
P('normal breath), at the default master volume, median of 5 renders (hits use random noise, plucks a random');
P('excitation). Target: peak -3 dBFS (the tanpura, a backing drone, -9 dBFS). The trims live in `LEVEL` in');
P('`index.html` and come from `npm run calibrate`.');
P('');
P('RMS depends on the kind of sound: short hits land near the -18 dBFS target, sustained tones are denser');
P('(a held sawtooth has only 5-8 dB between peak and RMS), so they sit nearer -10 dBFS at the same -3 dBFS peak.');
P('Peak is what a speaker clips on, so every sound is matched on peak and the RMS is reported.');
P('');
P(row(['Sound', 'Peak (dBFS)', 'RMS (dBFS)', 'Peak spread over 5 renders (dB)']));
P(row(['---', '---:', '---:', '---:']));
loud.forEach((r) => P(row([r.name, r.peak.toFixed(1), r.rms.toFixed(1), r.peakSpread.toFixed(1)])));
const pk = loud.filter((r) => r.target === -3).map((r) => r.peak);
P('');
P(`Peaks: median ${pk.slice().sort((a, b) => a - b)[pk.length >> 1].toFixed(1)} dBFS, ${pk.filter((p) => Math.abs(p + 3) <= 1).length} of ${pk.length} within 1 dB of -3 dBFS, ` +
  `${pk.filter((p) => Math.abs(p + 3) <= 2).length} within 2 dB. The outliers are noise-based hits whose peak changes from hit to hit.`);
P('');

P('## Master chain');
P('');
P('`master volume -> limiter (DynamicsCompressor: threshold -6 dB, ratio 20, 2 ms attack, 150 ms release) -> make-up');
P('gain (+2 dB; the browser adds its own make-up of about +3 dB) -> soft ceiling (linear to -2 dBFS, never above -1 dBFS)`.');
P('A single note at the default volume passes through untouched (+4.8 dB overall). Chords and stacked hits are held');
P('down by the limiter, and the ceiling catches anything faster than its attack; the limiter test above shows every');
P('stress case peaking at -1.0 dBFS with no clipped samples, even at 150% volume. The master volume slider in');
P('Settings runs 0-150%, defaults to 100%, and is remembered.');
P('');
P('**First note after start-up.** A new compressor starts fully clamped and needs about 0.2 s to open, which made the');
P('first note after the app woke up about 10 dB quiet. For the first 0.3 s the app now sends audio through a plain gain');
P('path with the same +4.8 dB, then crossfades to the limiter.');
P('');
fs.writeFileSync(path.join(__dirname, '..', 'TESTING.md'), out.join('\n'));
console.log('wrote TESTING.md');
